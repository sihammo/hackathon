/// Represents a route calculated by SolveX, comparing safety levels and black points.
class SafeRoute {
  final String id;
  final String title;
  final String subtitle;
  final double distanceKm;
  final int durationMinutes;
  final int blackPointsCount;
  final int blackPointsAvoided;
  final int safetyScore; // 0 to 100
  final bool isSafe;
  final Color color;
  final List<LatLng> points;
  final String explanation;
  final String highlights;

  const SafeRoute({
    required this.id,
    required this.title,
    required this.subtitle,
    required this.distanceKm,
    required this.durationMinutes,
    required this.blackPointsCount,
    required this.blackPointsAvoided,
    required this.safetyScore,
    required this.isSafe,
    required this.color,
    required this.points,
    required this.explanation,
    required this.highlights,
  });

  SafeRoute copyWith({
    String? id,
    String? title,
    String? subtitle,
    double? distanceKm,
    int? durationMinutes,
    int? blackPointsCount,
    int? blackPointsAvoided,
    int? safetyScore,
    bool? isSafe,
    Color? color,
    List<LatLng>? points,
    String? explanation,
    String? highlights,
  }) {
    return SafeRoute(
      id: id ?? this.id,
      title: title ?? this.title,
      subtitle: subtitle ?? this.subtitle,
      distanceKm: distanceKm ?? this.distanceKm,
      durationMinutes: durationMinutes ?? this.durationMinutes,
      blackPointsCount: blackPointsCount ?? this.blackPointsCount,
      blackPointsAvoided: blackPointsAvoided ?? this.blackPointsAvoided,
      safetyScore: safetyScore ?? this.safetyScore,
      isSafe: isSafe ?? this.isSafe,
      color: color ?? this.color,
      points: points ?? this.points,
      explanation: explanation ?? this.explanation,
      highlights: highlights ?? this.highlights,
    );
  }
}

/// A destination with pre-analyzed safe vs risky routes avoiding accident black points.
class SafeDestination {
  final String id;
  final String name;
  final String nameAr;
  final String city;
  final String category;
  final IconData icon;
  final LatLng targetLocation;
  final SafeRoute safeRoute;
  final SafeRoute riskyRoute;

  const SafeDestination({
    required this.id,
    required this.name,
    required this.nameAr,
    required this.city,
    required this.category,
    required this.icon,
    required this.targetLocation,
    required this.safeRoute,
    required this.riskyRoute,
  });

  SafeDestination copyWith({
    String? id,
    String? name,
    String? nameAr,
    String? city,
    String? category,
    IconData? icon,
    LatLng? targetLocation,
    SafeRoute? safeRoute,
    SafeRoute? riskyRoute,
  }) {
    return SafeDestination(
      id: id ?? this.id,
      name: name ?? this.name,
      nameAr: nameAr ?? this.nameAr,
      city: city ?? this.city,
      category: category ?? this.category,
      icon: icon ?? this.icon,
      targetLocation: targetLocation ?? this.targetLocation,
      safeRoute: safeRoute ?? this.safeRoute,
      riskyRoute: riskyRoute ?? this.riskyRoute,
    );
  }
}

