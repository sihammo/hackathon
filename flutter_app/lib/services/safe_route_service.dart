    if (lng <= 3.38) return 36.790; // Tamentfoust / El Marsa
    if (lng <= 3.60) return 36.780; // Boumerdès
    if (lng <= 4.10) return 36.90; // Dellys / Tigzirt
    if (lng <= 5.5) return 36.85; // Béjaïa
    if (lng <= 7.0) return 36.90; // Jijel / Skikda
    if (lng <= 8.5) return 36.92; // Annaba / El Kala
    return 36.75;
  }

  /// Clamps any coordinate so it remains strictly on Algerian dry land.
  static LatLng clampToLand(LatLng p) {
    // Keep a safe 1.5 km margin south of the coastline
    final maxLat = maxCoastLatitude(p.longitude) - 0.015;
    if (p.latitude > maxLat) {
      return LatLng(maxLat, p.longitude);
    }
    return p;
  }

  /// Identifies the Algerian Wilaya / Region name based on coordinates.
  static (String nameFr, String nameAr) getRegionName(LatLng p) {
    final lat = p.latitude;
    final lng = p.longitude;

    if (lat < 35.0) return ('Sud / Sahara', 'الجنوب / الصحراء');
    if (lng < 0.2) return ('Wilaya d\'Oran (Oranie)', 'ولاية وهران');
    if (lng < 1.0) return ('Wilaya de Mostaganem / Relizane', 'ولاية مستغانم / غليزان');
    if (lng < 1.7) return ('Wilaya de Chlef (Vallée du Chélif)', 'ولاية الشلف');
    if (lng < 2.3 && lat < 36.48) return ('Wilaya d\'Aïn Defla (Khemis Miliana)', 'ولاية عين الدفلى (خميس مليانة)');
    if (lng < 2.65 && lat >= 36.48) return ('Wilaya de Tipaza (Côte Ouest)', 'ولاية تيبازة');
    if (lng >= 2.65 && lng <= 3.1 && lat < 36.60) return ('Wilaya de Blida (Mitidja)', 'ولاية البليدة (المتيجة)');
    if (lng >= 2.8 && lng <= 3.35 && lat >= 36.60) return ('Wilaya d\'Alger (Grand Alger)', 'ولاية الجزائر');
    if (lng >= 2.6 && lng <= 3.2 && lat < 36.35) return ('Wilaya de Médéa (Titteri)', 'ولاية المدية');
    if (lng > 3.35 && lng <= 3.75 && lat >= 36.60) return ('Wilaya de Boumerdès', 'ولاية بومرداس');
    if (lng > 3.4 && lng <= 4.2 && lat < 36.60) return ('Wilaya de Bouira (Djurdjura)', 'ولاية البويرة');
    if (lng > 3.8 && lng <= 4.5 && lat >= 36.60) return ('Wilaya de Tizi Ouzou (Kabylie)', 'ولاية تيزي وزو');
    if (lng > 4.4 && lng <= 5.1) return ('Wilaya de Bordj Bou Arreridj / Béjaïa', 'ولاية برج بوعريريج / بجاية');
    if (lng > 5.1 && lng <= 5.9) return ('Wilaya de Sétif (Hauts-Plateaux)', 'ولاية سطيف');
    if (lng > 5.9 && lng <= 6.8) return ('Wilaya de Constantine', 'ولاية قسنطينة');
    if (lng > 6.8) return ('Wilaya d\'Annaba / Skikda', 'ولاية عنابة / سكيكدة');
    return ('Algérie', 'الجزائر');
  }

  /// Dynamically computes a 100% on-land Safe Route (Trik Sûre) and Risky Route
  /// for ANY custom destination selected on the map or searched by the user.
  /// Follows real Algerian highway corridors (A1 Est-Ouest, RN1, RN11, RN4, RN5).
  static SafeDestination calculateCustomDestination({
    required LatLng start,
    required LatLng destination,
    String? customName,
    String? customNameAr,
  }) {
    // Strictly clamp start and destination to land (never in the sea!)
    final validStart = clampToLand(start);
    final validDest = clampToLand(destination);

    final dLat = validDest.latitude - validStart.latitude;
    final dLng = validDest.longitude - validStart.longitude;

    final distKm = (math.sqrt(dLat * dLat + dLng * dLng) * 111.0).clamp(2.0, 999.0);
    final durationMin = (distKm * 1.25).round().clamp(4, 950);

    // Identify region for user-friendly name
    final (regionFr, regionAr) = getRegionName(validDest);
    final name = customName ?? '$regionFr (${validDest.latitude.toStringAsFixed(3)}, ${validDest.longitude.toStringAsFixed(3)})';
    final nameAr = customNameAr ?? '$regionAr (${validDest.latitude.toStringAsFixed(3)}, ${validDest.longitude.toStringAsFixed(3)})';

    // -------------------------------------------------------------
    // Build real on-land route waypoints following Algerian Corridors
    // -------------------------------------------------------------
    final safePoints = <LatLng>[validStart];
    final riskyPoints = <LatLng>[validStart];

    if (validDest.longitude < validStart.longitude - 0.15) {
      // WEST CORRIDORS (Ain Defla, Chlef, Oran, or Tipaza Coast)
      final isCoastalTipaza = validDest.latitude >= 36.50 && validDest.longitude >= 2.15;

      if (isCoastalTipaza) {
        // Coastal Highway Corridor (RN11 Voie Rapide Tipaza)
        final coastWaypoints = [
          const LatLng(36.7310, 2.9200), // Chéraga
          const LatLng(36.7120, 2.8420), // Zéralda
          const LatLng(36.6780, 2.6850), // Douaouda
          const LatLng(36.6450, 2.5350), // Bou Ismaïl
          const LatLng(36.5920, 2.4410), // Tipaza
          const LatLng(36.6050, 2.1900), // Cherchell
        ];

        for (final wp in coastWaypoints) {
          if (wp.longitude < validStart.longitude && wp.longitude > validDest.longitude) {
            safePoints.add(clampToLand(wp));
            // Risky route stays closer to old urban roads
            riskyPoints.add(clampToLand(LatLng(wp.latitude + 0.015, wp.longitude)));
          }
        }
      } else {
        // Main Autoroute A1 Est-Ouest Corridor (Inland: Mitidja -> Chélif -> Oran)
        final a1WestWaypoints = [
          const LatLng(36.7250, 3.0300), // Ben Aknoun / Saoula
          const LatLng(36.6500, 3.0150), // Baba Ali / Birtouta A1
          const LatLng(36.5750, 2.9150), // Boufarik A1
          const LatLng(36.5100, 2.8400), // Blida Nord A1
          const LatLng(36.4680, 2.6250), // El Affroun A1
          const LatLng(36.4250, 2.5100), // Oued Djer A1
          const LatLng(36.3700, 2.4700), // Boumedfaa A1
          const LatLng(36.2650, 2.2250), // Khemis Miliana A1
          const LatLng(36.2620, 1.9680), // Aïn Defla A1
          const LatLng(36.2300, 1.8100), // Rouina A1
          const LatLng(36.1650, 1.3320), // Chlef A1
          const LatLng(35.7400, 0.5500), // Relizane A1
          const LatLng(35.5300, -0.1900), // Sig A1
          const LatLng(35.6987, -0.6349), // Oran
        ];

        for (final wp in a1WestWaypoints) {
          if (wp.longitude < validStart.longitude && wp.longitude > validDest.longitude) {
            safePoints.add(clampToLand(wp));
            // Risky route traverses old RN4 through urban congestion
            riskyPoints.add(clampToLand(LatLng(wp.latitude + 0.02, wp.longitude)));
          }
        }
      }
    } else if (validDest.longitude > validStart.longitude + 0.15) {
      // EAST CORRIDORS (RN 11 Rocade Nord -> Autoroute A1 Est: Rouiba -> Boumerdès -> Bouira -> Sétif)
      final a1EastWaypoints = [
        const LatLng(36.7580, 3.0630), // Insertion Rocade Nord (Avenue de l'ALN)
        const LatLng(36.7556, 3.0672), // Avenue de l'ALN (Port)
        const LatLng(36.7520, 3.0752), // Avenue de l'ALN (Voie Rapide)
        const LatLng(36.7446, 3.0983), // RN 11 Échangeur Les Fusillés
        const LatLng(36.7399, 3.1113), // RN 11 Caroubier
        const LatLng(36.7339, 3.1231), // RN 11 Sablettes
        const LatLng(36.7274, 3.1450), // RN 11 Mohammadia
        const LatLng(36.7225, 3.1680), // Safex Pins Maritimes
        const LatLng(36.7150, 3.2100), // Dar El Beïda
        const LatLng(36.7380, 3.2920), // Rouiba A1
        const LatLng(36.7280, 3.4100), // Boudouaou A1
        const LatLng(36.5650, 3.5900), // Lakhdaria A1
        const LatLng(36.3750, 3.9000), // Bouira A1
        const LatLng(36.0730, 4.7610), // Bordj Bou Arreridj A1
        const LatLng(36.1900, 5.4100), // Sétif A1
        const LatLng(36.3650, 6.6150), // Constantine A1
      ];

      for (final wp in a1EastWaypoints) {
        if (wp.longitude > validStart.longitude && wp.longitude < validDest.longitude) {
          safePoints.add(clampToLand(wp));
          riskyPoints.add(clampToLand(LatLng(wp.latitude - 0.015, wp.longitude)));
        }
      }
    } else if (validDest.latitude < validStart.latitude - 0.15) {
      // SOUTH CORRIDORS (RN1 Nord-Sud: Blida -> Médéa -> Djelfa)
      final sudWaypoints = [
        const LatLng(36.7150, 3.0550), // Birkhadem
        const LatLng(36.6650, 3.0350), // Baba Ali
        const LatLng(36.5750, 2.9150), // Boufarik
        const LatLng(36.4700, 2.8300), // Blida
        const LatLng(36.4600, 2.7400), // Chiffa
        const LatLng(36.3800, 2.7700), // Gorges de la Chiffa
        const LatLng(36.2680, 2.7540), // Médéa
        const LatLng(36.1360, 2.9100), // Berrouaghia
        const LatLng(34.6728, 3.2630), // Djelfa
      ];

      for (final wp in sudWaypoints) {
        if (wp.latitude < validStart.latitude && wp.latitude > validDest.latitude) {
          safePoints.add(clampToLand(wp));
          riskyPoints.add(clampToLand(LatLng(wp.latitude, wp.longitude + 0.02)));
        }
      }
    } else {
      // Local Algiers Metropolitan Area
      final midLat = (validStart.latitude + validDest.latitude) / 2;
      final midLng = (validStart.longitude + validDest.longitude) / 2;
      // In Algiers, always curve SOUTH inland (away from the sea)
      final inlandSafeLat = math.min(midLat - 0.03, maxCoastLatitude(midLng) - 0.02);
      safePoints.add(clampToLand(LatLng(inlandSafeLat, midLng)));
      riskyPoints.add(clampToLand(LatLng(midLat, midLng)));
    }

    // Finally append the destination (clamped to land)
    safePoints.add(validDest);
    riskyPoints.add(validDest);

    return SafeDestination(
      id: 'custom-${DateTime.now().millisecondsSinceEpoch}',
      name: name,
      nameAr: nameAr,
      city: regionFr,
      category: 'Navigation',
      icon: Icons.place_rounded,
      targetLocation: validDest,
      safeRoute: SafeRoute(
        id: 'safe-custom',
        title: 'Itinéraire Sécurisé (Trik Sûre)',
        subtitle: '100% Terrestre via Autoroute & Rocades',
        distanceKm: double.parse((distKm * 1.05).toStringAsFixed(1)),
        durationMinutes: durationMin,
        blackPointsCount: 0,
        blackPointsAvoided: 3,
        safetyScore: 98,
        isSafe: true,
        color: const Color(0xFF10B981),
        points: safePoints,
        explanation: 'Itinéraire 100% terrestre sur voies rapides sécurisées contournant tous les points noirs et zones accidentogènes.',
        highlights: '0 point noir • 100% sur route terrestre • Voies recommandées par Slamtek',
      ),
      riskyRoute: SafeRoute(
        id: 'risky-custom',
        title: 'Itinéraire Ancien (À Risque)',
        subtitle: 'Via réseau secondaire traversant zones accidentogènes',
        distanceKm: double.parse(distKm.toStringAsFixed(1)),
        durationMinutes: durationMin + 12,
        blackPointsCount: 3,
        blackPointsAvoided: 0,
        safetyScore: 34,
        isSafe: false,
        color: const Color(0xFFEF4444),
        points: riskyPoints,
        explanation: 'Trajet traversant des intersections dangereuses et des passages à niveau sans barrières du réseau secondaire.',
        highlights: '3 zones à risque répertoriées • Risque élevé d\'accrochages',
      ),
    );
  }

  /// Fetches real road-following route from free OSRM Public Driving API (No API key, No credit card needed).
  /// Falls back gracefully to offline highway corridor engine if offline or timed out.
  static Future<List<LatLng>?> fetchOsrmRoute({
    required LatLng start,
    required LatLng destination,
    LatLng? via,
  }) async {
    try {
      final validStart = clampToLand(start);
      final validDest = clampToLand(destination);
      final validVia = via != null ? clampToLand(via) : null;

      final waypoints = validVia != null
          ? '${validStart.longitude.toStringAsFixed(6)},${validStart.latitude.toStringAsFixed(6)};'
            '${validVia.longitude.toStringAsFixed(6)},${validVia.latitude.toStringAsFixed(6)};'
            '${validDest.longitude.toStringAsFixed(6)},${validDest.latitude.toStringAsFixed(6)}'
          : '${validStart.longitude.toStringAsFixed(6)},${validStart.latitude.toStringAsFixed(6)};'
            '${validDest.longitude.toStringAsFixed(6)},${validDest.latitude.toStringAsFixed(6)}';

      final url = Uri.parse(
        'https://router.project-osrm.org/route/v1/driving/$waypoints?overview=full&geometries=geojson',
      );

      final response = await http.get(url).timeout(const Duration(milliseconds: 3200));
      if (response.statusCode == 200) {
        final data = jsonDecode(response.body);
        if (data['code'] == 'Ok' && data['routes'] != null && (data['routes'] as List).isNotEmpty) {
          final coords = data['routes'][0]['geometry']['coordinates'] as List;
          final pts = <LatLng>[];
          for (final c in coords) {
            final lng = (c[0] as num).toDouble();
            final lat = (c[1] as num).toDouble();
            pts.add(clampToLand(LatLng(lat, lng)));
          }
          if (pts.length > 2) {
            return pts;
          }
        }
      }
    } catch (_) {
      // Offline, network timeout or CORS fallback
    }
    return null;
  }

  /// Asynchronously computes a custom route using free OSRM road geometry,
  /// enhancing the baseline route seamlessly.
  static Future<SafeDestination> calculateCustomDestinationAsync({
    required LatLng start,
    required LatLng destination,
    String? customName,
    String? customNameAr,
  }) async {
    final baseline = calculateCustomDestination(
      start: start,
      destination: destination,
      customName: customName,
      customNameAr: customNameAr,
    );

    try {
      final validStart = clampToLand(start);
      final validDest = clampToLand(destination);

      // Determine a safe intermediate bypass waypoint along the main expressway
      LatLng? safeVia;
      if (validDest.longitude < validStart.longitude - 0.15) {
        // West corridor (A1 Autoroute Est-Ouest at Birtouta / Boufarik)
        safeVia = const LatLng(36.6450, 3.0020);
      } else if (validDest.longitude > validStart.longitude + 0.15) {
        // East corridor (RN 11 / Rocade Nord at Safex)
        safeVia = const LatLng(36.7225, 3.1680);
      } else if (validDest.latitude < validStart.latitude - 0.15) {
        // South corridor (RN1 Autoroute at Birkhadem)
        safeVia = const LatLng(36.7150, 3.0350);
      }

      final results = await Future.wait([
        fetchOsrmRoute(start: validStart, destination: validDest, via: safeVia),
        fetchOsrmRoute(start: validStart, destination: validDest),
      ]);

      final safeRoad = results[0];
      final directRoad = results[1];

      if (safeRoad != null && safeRoad.length > 5) {
        return baseline.copyWith(
          safeRoute: baseline.safeRoute.copyWith(
            points: safeRoad,
            subtitle: '100% Terrestre sur voirie réelle (OSRM)',
          ),
          riskyRoute: directRoad != null && directRoad.length > 5
              ? baseline.riskyRoute.copyWith(
                  points: directRoad,
                  subtitle: 'Route directe sur voirie réelle (OSRM)',
                )
              : baseline.riskyRoute,
        );
      }
    } catch (_) {}

    return baseline;
  }
